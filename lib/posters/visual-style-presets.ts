function buildSourcePromptBlock(input: { motherPrompt: string; miniProgramPrompt?: string }) {
  return [
    "【原始母提示词风格】",
    input.motherPrompt,
    input.miniProgramPrompt ? "【小程序适配变量语义】" : "",
    input.miniProgramPrompt || "",
    "【接入约束】",
    SOURCE_PROMPT_GUARD,
  ]
    .filter(Boolean)
    .join("\n")
}

function buildPromptSource(input: PosterVisualStylePromptSource) {
  return {
    promptSource: input,
    promptBlock: buildSourcePromptBlock(input),
  }
}

